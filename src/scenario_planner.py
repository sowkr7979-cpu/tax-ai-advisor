"""src/scenario_planner.py — '경우의 수' 기반 절세전략·세무리스크 의사결정 모델.

법무·세무 실무서의 사고방식(어떤 거래·사건이 발생하면, 핵심 조건들을 **분기(경우의 수)**
로 따져 각 분기마다 ① 세무리스크(과세·부인·추징)와 ② 절세전략·리스크관리(요건 충족·증빙·
시점)를 도출)를 **데이터 구조**로 옮긴 것이다. 텍스트만으로는 분기 추론이 한눈에 안 들어오므로
상위 모듈(``scenario_flowchart``)이 이 구조를 **플로우차트**로 그린다.

원칙(프로젝트 불변식과 일관):
* 근거 날조 금지 — 각 분기 결론은 실제 법령 조문/실무가이드 근거 라벨을 단다. 본 모듈의
  시나리오는 **AI 추론 초안**이며 회계사 검토(HITL)를 전제로 한다(``review_required``).
* 금액은 가상 dummy(예시 회사 '가나다정밀(주)'). 추론 구조·근거가 산출물의 본체다.

데이터 모델
-----------
``Scenario`` = 하나의 거래/사건. ``gates``(순차 의사결정 분기) + ``leaves``(경우의 수별 결론)
+ 권고 case 의 사후관리/필요 action/실행 plan + (선택) 회계처리 분개 예시.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Optional

# 위험 등급(플로우차트·표 색상 매핑) — 허용값 고정(검증용).
RISK_LEVELS = ("안전", "주의", "위험")


@dataclass(frozen=True)
class Gate:
    """순차 의사결정 분기 한 칸. 'pass' 답이면 아래 게이트로, 'risk' 답이면 리스크 분기로."""
    key: str            # "D1"
    question: str       # 분기 질문(의사결정)
    pass_label: str     # 통과(아래로 진행) 분기 라벨  예) "예 · 적정"
    risk_label: str     # 리스크(옆으로 빠짐) 분기 라벨  예) "아니오"
    risk_title: str     # 리스크 결과 박스 제목       예) "부당행위계산부인"
    risk_detail: str    # 리스크 결과 박스 본문(리스크+관리 요지)


@dataclass(frozen=True)
class Leaf:
    """경우의 수(분기 경로) 한 가지에 대한 결론 — 리스크 + 절세전략/리스크관리 + 근거."""
    case_label: str     # "경우 ①"
    path: str           # 분기 경로 요약  예) "소각목적·시가·균등취득"
    risk_level: str     # RISK_LEVELS 중 하나
    tax_risk: str       # 세무리스크(무엇이 과세/부인되나)
    management: str     # 절세전략·리스크관리(요건·증빙·시점)
    basis: tuple[str, ...]  # 근거 라벨(법령 조문/가이드)


@dataclass(frozen=True)
class PlanStep:
    when: str           # 시점  예) "D-0 ~ D+30"
    what: str           # 행위
    effect: str         # 세무효과/목적


@dataclass(frozen=True)
class JournalLine:
    account: str
    debit: float
    credit: float


@dataclass(frozen=True)
class JournalIllustration:
    """권고 case 의 회계처리 분개 예시(가상 금액). 분개장 dummy 연계."""
    title: str
    note: str
    lines: tuple[JournalLine, ...]


@dataclass(frozen=True)
class Scenario:
    key: str
    title: str          # "비상장법인 자기주식 취득"
    trigger: str        # 어떤 상황에서 이 의사결정이 필요한가(짧은 한 줄)
    summary: str        # 한 줄 추론 요지
    gates: tuple[Gate, ...]
    safe_title: str     # 모든 게이트 통과 시 결과(녹색)
    safe_detail: str
    leaves: tuple[Leaf, ...]
    citations: tuple[str, ...]      # 시나리오 근거 법령(조문 라벨)
    recommended_case: str           # 권고 경로 case_label
    aftercare: tuple[str, ...]      # 사후관리(post-management)
    actions: tuple[str, ...]        # 필요 action(즉시)
    plan: tuple[PlanStep, ...]      # 미래 plan(실행 타임라인)
    journal: Optional[JournalIllustration] = None
    review_required: bool = True    # 회계사 검토 전제(HITL)
    rag_query: str = ""             # 내부 RAG DB 근거 회수용 질의(없으면 title 사용)
    facts: str = ""                 # [사실관계] — 회사 그라운딩 사실관계(합성). 없으면 trigger 사용

    def validate(self) -> None:
        """구조 무결성 — 게이트≥2, 경우의 수≥2, 위험등급 허용값, 근거 비어있지 않음."""
        if len(self.gates) < 2:
            raise ValueError(f"{self.key}: 게이트는 2개 이상이어야 합니다(경우의 수 분기).")
        if len(self.leaves) < 2:
            raise ValueError(f"{self.key}: 경우의 수(leaf)는 2개 이상이어야 합니다.")
        labels = {lf.case_label for lf in self.leaves}
        if self.recommended_case not in labels:
            raise ValueError(f"{self.key}: 권고 case '{self.recommended_case}' 가 경우의 수에 없습니다.")
        for lf in self.leaves:
            if lf.risk_level not in RISK_LEVELS:
                raise ValueError(f"{self.key}/{lf.case_label}: 위험등급 '{lf.risk_level}' 불허(허용 {RISK_LEVELS}).")
            # 근거는 '있기만' 해선 안 되고 **공백 아닌 실제 라벨**이어야 한다(빈/공백 근거로
            # 날조방지 가드를 우회하는 것을 차단 — codex 적발).
            if not lf.basis or not all(str(b).strip() for b in lf.basis):
                raise ValueError(f"{self.key}/{lf.case_label}: 근거(basis)가 비었거나 공백입니다(날조 방지 — 근거 필수).")
        if not self.citations or not all(str(c).strip() for c in self.citations):
            raise ValueError(f"{self.key}: 시나리오 근거 법령이 비었거나 공백입니다.")


